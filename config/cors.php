<?php

return [

    /*
    |--------------------------------------------------------------------------
    | CORS Paths
    |--------------------------------------------------------------------------
    |
    | CORS を付与するパス。
    | Bearer API は /api/* が対象。
    | （cookie運用に戻す可能性があるなら sanctum/csrf-cookie も残してOK）
    |
    */

    'paths' => ['api/*', 'sanctum/csrf-cookie'],

    /*
    |--------------------------------------------------------------------------
    | Allowed Methods
    |--------------------------------------------------------------------------
    */

    'allowed_methods' => ['*'],

    /*
    |--------------------------------------------------------------------------
    | Allowed Origins
    |--------------------------------------------------------------------------
    |
    | 例:
    | CORS_ALLOWED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173
    |
    */

    'allowed_origins' => array_values(array_filter(array_map(
        'trim',
        explode(',', env('CORS_ALLOWED_ORIGINS', 'http://localhost:5173'))
    ))),

    'allowed_origins_patterns' => [],

    /*
    |--------------------------------------------------------------------------
    | Allowed Headers
    |--------------------------------------------------------------------------
    |
    | Bearer トークン運用では Authorization が必要。
    | '*' で許可しておく（運用で厳格化したいなら明示列挙でもOK）。
    |
    */

    'allowed_headers' => ['*'],

    /*
    |--------------------------------------------------------------------------
    | Exposed Headers
    |--------------------------------------------------------------------------
    */

    'exposed_headers' => [],

    /*
    |--------------------------------------------------------------------------
    | Max Age
    |--------------------------------------------------------------------------
    */

    'max_age' => 0,

    /*
    |--------------------------------------------------------------------------
    | Supports Credentials
    |--------------------------------------------------------------------------
    |
    | Bearerトークン運用なら false が基本。
    | cookie運用（Sanctum SPA）に寄せるなら true にし、allowed_origins を厳格化。
    |
    */

    'supports_credentials' => false,
];
